// =====================================================================
//  Gera banco/supabase.sql: o banco do sistema pronto para o Supabase
//
//  O arquivo junta:
//    1. a estrutura de banco/schema.sql convertida para PostgreSQL
//    2. os dados de teste de banco/seed.sql (as datas sao calculadas a
//       partir do dia em que este script roda)
//    3. a tabela de sessoes de login e a protecao RLS
//
//  Como usar:  node ferramentas/gerar-sql-supabase.js
//  Depois:     Supabase > SQL Editor > colar banco/supabase.sql > Run
// =====================================================================

import { DatabaseSync } from 'node:sqlite';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { traduzir, literal } from '../servidor/traduzir-sql.js';

const AQUI = dirname(fileURLToPath(import.meta.url));
const PASTA = join(AQUI, '..', 'banco');
const schema = readFileSync(join(PASTA, 'schema.sql'), 'utf8');
const seed = readFileSync(join(PASTA, 'seed.sql'), 'utf8');

// Remove comentarios "--" que estao fora de aspas
function semComentarios(sql) {
  return sql.split('\n').map((linha) => {
    let dentro = false;
    for (let i = 0; i < linha.length; i++) {
      if (linha[i] === "'") dentro = !dentro;
      if (!dentro && linha[i] === '-' && linha[i + 1] === '-') return linha.slice(0, i).trimEnd();
    }
    return linha;
  }).filter((l) => l.trim() !== '').join('\n');
}

// ---- 1. estrutura ---------------------------------------------------
let ddl = semComentarios(schema)
  .replace(/^\s*PRAGMA[^;]*;\s*$/gim, '')
  .replace(/INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/gi, 'integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  .replace(/\bREAL\b/g, 'numeric');
ddl = traduzir(ddl);
// O PostgreSQL exige no GROUP BY toda coluna que nao e agregada
ddl = ddl.replace(/GROUP BY c\.vendedor_id, competencia/, 'GROUP BY c.vendedor_id, f.nome, f.percentual_comissao, competencia');
// Visoes respeitam a protecao (RLS) de quem consulta
ddl = ddl.replace(/CREATE VIEW (\w+) AS/g, 'CREATE VIEW $1 WITH (security_invoker = true) AS');

const tabelas = [...schema.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)/g)].map((m) => m[1]);
const visoes = [...schema.matchAll(/CREATE VIEW (\w+)/g)].map((m) => m[1]);

// ---- 2. dados de teste ----------------------------------------------
const db = new DatabaseSync(':memory:');
db.exec(schema);
db.exec(seed);
const linhasSeed = [];
for (const t of tabelas) {
  const linhas = db.prepare(`SELECT * FROM ${t}`).all();
  if (linhas.length === 0) continue;
  const colunas = Object.keys(linhas[0]);
  linhasSeed.push(`-- ${t} (${linhas.length})`);
  for (const l of linhas) {
    linhasSeed.push(`INSERT INTO ${t} (${colunas.join(', ')}) VALUES (${colunas.map((c) => literal(l[c])).join(', ')});`);
  }
  if (colunas.includes('id')) {
    linhasSeed.push(`SELECT setval(pg_get_serial_sequence('${t}', 'id'), (SELECT max(id) FROM ${t}));`);
  }
}

// ---- 3. montagem ----------------------------------------------------
const hoje = new Date().toISOString().slice(0, 10);
const saida = `-- =====================================================================
--  MARELO MOTOS - banco para o SUPABASE (PostgreSQL)
--  Gerado por ferramentas/gerar-sql-supabase.js em ${hoje}. Nao editar a mao.
--
--  Como usar: Supabase > SQL Editor > New snippet > colar tudo > Run
--  ATENCAO: apaga e recria todas as tabelas do sistema.
--  Senha dos usuarios de teste: marelo123 (o sistema grava o hash no
--  primeiro acesso; o arquivo nao contem senha).
-- =====================================================================

-- 0. limpeza (inclui as tabelas do script de teste anterior)
DROP VIEW IF EXISTS ${visoes.join(', ')} CASCADE;
DROP TABLE IF EXISTS sessao, ${[...tabelas].reverse().join(', ')} CASCADE;

-- 1. estrutura (convertida de banco/schema.sql)
${ddl.trim()}

-- 2. sessoes de login (a Vercel nao guarda nada na memoria entre acessos)
CREATE TABLE sessao (
  token      text   PRIMARY KEY,
  usuario    text   NOT NULL,
  expira_em  bigint NOT NULL
);

-- 3. dados de teste (de banco/seed.sql)
${linhasSeed.join('\n')}

-- 4. protecao: com RLS ligado e sem POLICY, a chave publica do Supabase
--    nao le nem grava nada. Quem acessa o banco e so o servidor do
--    sistema na Vercel, pela DATABASE_URL (que nunca vai para o codigo).
${[...tabelas, 'sessao'].map((t) => `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;`).join('\n')}

-- 5. conferencia
SELECT 'tabelas' AS item, count(*) AS total FROM pg_tables WHERE schemaname = 'public'
UNION ALL SELECT 'clientes', count(*) FROM cliente
UNION ALL SELECT 'motos', count(*) FROM moto;
`;

writeFileSync(join(PASTA, 'supabase.sql'), saida);
console.log(`  Pronto: banco/supabase.sql (${tabelas.length} tabelas + sessao, ${linhasSeed.length} linhas de dados)`);
